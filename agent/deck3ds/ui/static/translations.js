export function initialLocale(storage, browserLanguage) {
  try {
    const saved = (storage === undefined ? localStorage : storage).getItem(LOCALE_KEY);
    if (saved === 'fr' || saved === 'en') return saved;
  } catch (error) {
    // La langue du navigateur reste disponible si le stockage est refusé.
  }
  const language = browserLanguage === undefined ? navigator.language : browserLanguage;
  return String(language || '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export function translate(locale, key, values = {}) {
  const table = COPY[locale] || COPY.fr;
  let text = table[key] || COPY.fr[key] || key;
  Object.entries(values).forEach(([name, value]) => {
    text = text.replaceAll(`{${name}}`, String(value));
  });
  return text;
}
